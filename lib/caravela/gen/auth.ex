defmodule Caravela.Gen.Auth do
  @moduledoc """
  Generates the authentication stack for a `Caravela.Schema.Domain`
  whose authenticatable entity declares an `authenticatable` block.

  Emits:

    * `lib/<app>/<context>/auth.ex` — auth context (register, login,
      logout, sessions, API tokens, reset, confirm)
    * `lib/<app>/<context>/user_session.ex` — session schema
    * `lib/<web>/plugs/auth.ex` — plug pipeline
    * `lib/<web>/live/auth_hooks.ex` — LiveView `on_mount` hooks
    * `lib/<web>/controllers/auth_controller.ex` — auth endpoints
    * `priv/repo/migrations/<ts>_create_<context>_user_sessions.exs` —
      session tokens migration

  Returns a list of `{path, source}` tuples — the caller writes files.
  Files preserve content below the `# --- CUSTOM ---` marker on
  regeneration. The session migration is never merged (no marker) and
  is timestamped like any other migration.
  """

  alias Caravela.Schema.{AuthConfig, Domain, Entity}
  alias Caravela.{Gen, Naming}

  @context_template Path.expand("../../../priv/templates/auth_context.eex", __DIR__)
  @session_template Path.expand("../../../priv/templates/auth_session_schema.eex", __DIR__)
  @plugs_template Path.expand("../../../priv/templates/auth_plugs.eex", __DIR__)
  @live_hooks_template Path.expand("../../../priv/templates/auth_live_hooks.eex", __DIR__)
  @controller_template Path.expand("../../../priv/templates/auth_controller.eex", __DIR__)
  @migration_template Path.expand("../../../priv/templates/auth_migration.eex", __DIR__)

  @doc """
  Render all auth files. Raises if the domain has no authenticatable
  entity.

  Options:

    * `:root`      — project root, used to resolve existing files for
      custom-block preservation (defaults to `File.cwd!()`)
    * `:timestamp` — pin the migration timestamp (useful for tests)
  """
  def render_all(%Domain{} = domain, opts \\ []) do
    assert_auth!(domain)

    core = [
      render_context(domain, opts),
      render_session_schema(domain, opts),
      render_plugs(domain, opts),
      render_live_hooks(domain, opts),
      render_controller(domain, opts),
      render_migration(domain, opts)
    ]

    if Keyword.get(opts, :skip_ui, false) do
      core
    else
      core ++
        Caravela.Gen.AuthSvelte.render_all(domain, opts) ++
        Caravela.Gen.AuthLive.render_all(domain, opts)
    end
  end

  @doc """
  Return a ready-to-paste router snippet showing the public auth
  routes, protected `live_session`, and authenticated API scope.
  Printed by `mix caravela.gen.auth` after writing files.
  """
  def router_snippet(%Domain{} = domain) do
    assert_auth!(domain)

    web_v = versioned_web(domain)
    ctx = Naming.context_module(domain) |> inspect()
    auth = auth_module(domain) |> inspect()
    plugs = plugs_module(domain) |> inspect()
    hooks = live_hooks_module(domain) |> inspect()
    v_prefix = version_prefix(domain)

    """
    # --- BEGIN router additions (generated by caravela.gen.auth) ---

    # Plug aliases — add once near the top of your router.
    import #{plugs}

    # Public auth routes (LiveView pages + HTTP auth endpoints).
    scope "#{v_prefix}/auth", #{web_v} do
      pipe_through [:browser, :fetch_current_user]

      live "/login",                AuthLive.Login,         :index
      live "/register",             AuthLive.Register,      :index
      live "/reset-password",       AuthLive.ResetPassword, :request
      live "/reset-password/:token", AuthLive.ResetPassword, :confirm
      live "/confirm/:token",       AuthLive.ConfirmEmail,  :index
    end

    scope "#{v_prefix}/api/auth", #{web_v} do
      pipe_through [:api, :fetch_current_user]

      post "/register", AuthController, :register
      post "/login",    AuthController, :login
      delete "/logout", AuthController, :logout
    end

    # Protected LiveView routes — `current_user` is injected as a Svelte
    # prop on every mounted component.
    live_session :authenticated, on_mount: [{#{hooks}, :require_auth}] do
      scope "#{v_prefix}", #{web_v} do
        pipe_through [:browser, :fetch_current_user, :require_auth]

        live "/settings/tokens",   AuthLive.TokenManager, :index
        live "/settings/sessions", AuthLive.SessionList,  :index
        # … your other protected live routes here …
      end
    end

    # Authenticated API (session + bearer tokens both supported).
    scope "#{v_prefix}/api", #{web_v} do
      pipe_through [:api, :fetch_current_user, :require_auth]
      # resources "/books", Library.BookController
    end

    # Aliases referenced above:
    #   #{ctx} — context
    #   #{auth} — auth context
    # --- END router additions ---
    """
  end

  defp versioned_web(%Domain{} = domain) do
    base = Naming.web_module(domain)

    case Domain.version_segment(domain) do
      nil -> inspect(base)
      seg -> inspect(Module.concat(base, seg))
    end
  end

  defp version_prefix(%Domain{} = domain) do
    case Domain.version(domain) do
      nil -> ""
      v -> "/#{v}"
    end
  end

  # --- Context -----------------------------------------------------------

  @doc "Render the auth context module."
  def render_context(%Domain{} = domain, opts \\ []) do
    assert_auth!(domain)
    path = context_file_path(domain)
    existing = existing_path(path, opts)

    source =
      EEx.eval_file(@context_template, assigns: context_assigns(domain), trim: true)
      |> Gen.Custom.merge_with_file(existing, opts)
      |> Caravela.Gen.Format.try_format()
      |> Gen.Custom.stamp_header(generator: :auth_context)

    {path, source}
  end

  @doc "Render the session schema module."
  def render_session_schema(%Domain{} = domain, opts \\ []) do
    assert_auth!(domain)
    path = session_schema_file_path(domain)
    existing = existing_path(path, opts)

    source =
      EEx.eval_file(@session_template, assigns: session_assigns(domain), trim: true)
      |> Gen.Custom.merge_with_file(existing, opts)
      |> Caravela.Gen.Format.try_format()
      |> Gen.Custom.stamp_header(generator: :auth_session_schema)

    {path, source}
  end

  @doc "Render the Plug pipeline module."
  def render_plugs(%Domain{} = domain, opts \\ []) do
    assert_auth!(domain)
    path = plugs_file_path(domain)
    existing = existing_path(path, opts)

    source =
      EEx.eval_file(@plugs_template, assigns: plugs_assigns(domain), trim: true)
      |> Gen.Custom.merge_with_file(existing, opts)
      |> Caravela.Gen.Format.try_format()
      |> Gen.Custom.stamp_header(generator: :auth_plugs)

    {path, source}
  end

  @doc "Render the LiveView on_mount hooks module."
  def render_live_hooks(%Domain{} = domain, opts \\ []) do
    assert_auth!(domain)
    path = live_hooks_file_path(domain)
    existing = existing_path(path, opts)

    source =
      EEx.eval_file(@live_hooks_template, assigns: live_hooks_assigns(domain), trim: true)
      |> Gen.Custom.merge_with_file(existing, opts)
      |> Caravela.Gen.Format.try_format()
      |> Gen.Custom.stamp_header(generator: :auth_live_hooks)

    {path, source}
  end

  @doc "Render the auth HTTP controller."
  def render_controller(%Domain{} = domain, opts \\ []) do
    assert_auth!(domain)
    path = controller_file_path(domain)
    existing = existing_path(path, opts)

    source =
      EEx.eval_file(@controller_template, assigns: controller_assigns(domain), trim: true)
      |> Gen.Custom.merge_with_file(existing, opts)
      |> Caravela.Gen.Format.try_format()
      |> Gen.Custom.stamp_header(generator: :auth_controller)

    {path, source}
  end

  @doc "Render the session-tokens migration file."
  def render_migration(%Domain{} = domain, opts \\ []) do
    assert_auth!(domain)

    timestamp = Keyword.get(opts, :timestamp, default_timestamp())
    ctx_short = Naming.context_short(domain)

    module =
      Module.concat([
        "Caravela.Migrations",
        Naming.camelize(ctx_short),
        "CreateUserSessions"
      ])

    assigns = [
      module: module,
      table: session_table(domain),
      user_table: user_table(domain)
    ]

    source =
      EEx.eval_file(@migration_template, assigns: assigns, trim: true)
      |> Caravela.Gen.Format.try_format()

    path =
      Path.join(
        "priv/repo/migrations",
        "#{timestamp}_create_#{ctx_short}_user_sessions.exs"
      )

    {path, source}
  end

  # --- Naming helpers ----------------------------------------------------

  @doc false
  def auth_module(%Domain{} = domain), do: Module.concat(Naming.context_module(domain), Auth)

  @doc false
  def session_module(%Domain{} = domain),
    do: Module.concat(Naming.context_module(domain), UserSession)

  @doc false
  def plugs_module(%Domain{} = domain),
    do: Module.concat([Naming.web_module(domain), Plugs, Auth])

  @doc false
  def live_hooks_module(%Domain{} = domain),
    do: Module.concat([Naming.web_module(domain), Live, AuthHooks])

  @doc false
  def controller_module(%Domain{} = domain) do
    base =
      case Domain.version_segment(domain) do
        nil -> Naming.web_module(domain)
        seg -> Module.concat(Naming.web_module(domain), seg)
      end

    Module.concat(base, AuthController)
  end

  @doc false
  def session_table(%Domain{} = domain) do
    Naming.context_short(domain) <> "_user_sessions"
  end

  @doc false
  def user_table(%Domain{} = domain) do
    %Entity{name: name} = require_auth_entity!(domain)
    Naming.table_name(domain, name)
  end

  # --- Paths -------------------------------------------------------------

  defp context_file_path(%Domain{} = domain) do
    context_dir = context_base_dir(domain)
    Path.join(context_dir, "auth.ex")
  end

  defp session_schema_file_path(%Domain{} = domain) do
    context_dir = context_base_dir(domain)
    Path.join(context_dir, "user_session.ex")
  end

  defp context_base_dir(%Domain{} = domain) do
    parts =
      domain.module
      |> Naming.context_module()
      |> Module.split()
      |> Enum.map(&Macro.underscore/1)

    base = Path.join(["lib" | parts])

    case Domain.version(domain) do
      nil -> base
      v -> Path.join(base, v)
    end
  end

  defp plugs_file_path(%Domain{} = domain) do
    web = Naming.web_module(domain) |> Module.split() |> List.first() |> Macro.underscore()
    Path.join(["lib", web, "plugs", "auth.ex"])
  end

  defp live_hooks_file_path(%Domain{} = domain) do
    web = Naming.web_module(domain) |> Module.split() |> List.first() |> Macro.underscore()
    Path.join(["lib", web, "live", "auth_hooks.ex"])
  end

  defp controller_file_path(%Domain{} = domain) do
    web = Naming.web_module(domain) |> Module.split() |> List.first() |> Macro.underscore()

    case Domain.version(domain) do
      nil -> Path.join(["lib", web, "controllers", "auth_controller.ex"])
      v -> Path.join(["lib", web, "controllers", v, "auth_controller.ex"])
    end
  end

  # --- Assigns -----------------------------------------------------------

  defp context_assigns(%Domain{} = domain) do
    entity = require_auth_entity!(domain)
    cfg = entity.auth
    {session_ttl, remember_ttl, max_sessions} = session_values(cfg)

    [
      module: auth_module(domain),
      domain_module: domain.module,
      domain_short: domain.module,
      repo_module: Naming.repo_module(domain),
      user_module: Naming.entity_module(domain, entity.name),
      user_short: Naming.camelize(Naming.singularize(entity.name)),
      session_module: session_module(domain),
      session_short: "UserSession",
      multi_tenant: Domain.multi_tenant?(domain),
      confirm?: AuthConfig.confirm?(cfg),
      confirm_ttl_hours: ttl_hours(cfg.confirm, 24),
      reset?: AuthConfig.reset?(cfg),
      reset_ttl_hours: ttl_hours(cfg.reset, 1),
      api_token?: AuthConfig.api_token?(cfg),
      api_token_ttl_days: api_token_ttl_days(cfg),
      max_api_tokens: api_token_max(cfg),
      api_token_scopes: api_token_scopes(cfg),
      session_ttl_days: session_ttl,
      remember_me_ttl_days: remember_ttl,
      max_sessions: max_sessions,
      custom_marker: Gen.Custom.marker_block()
    ]
  end

  defp session_assigns(%Domain{} = domain) do
    entity = require_auth_entity!(domain)
    {session_ttl, remember_ttl, _} = session_values(entity.auth)

    [
      module: session_module(domain),
      domain_module: domain.module,
      table: session_table(domain),
      user_module: Naming.entity_module(domain, entity.name),
      session_ttl_days: session_ttl,
      remember_me_ttl_days: remember_ttl,
      custom_marker: Gen.Custom.marker_block()
    ]
  end

  defp plugs_assigns(%Domain{} = domain) do
    [
      module: plugs_module(domain),
      domain_module: domain.module,
      auth_module: auth_module(domain),
      custom_marker: Gen.Custom.marker_block()
    ]
  end

  defp live_hooks_assigns(%Domain{} = domain) do
    [
      module: live_hooks_module(domain),
      domain_module: domain.module,
      auth_module: auth_module(domain),
      custom_marker: Gen.Custom.marker_block()
    ]
  end

  defp controller_assigns(%Domain{} = domain) do
    cfg = require_auth_entity!(domain).auth

    [
      module: controller_module(domain),
      domain_module: domain.module,
      auth_module: auth_module(domain),
      multi_tenant: Domain.multi_tenant?(domain),
      confirm?: AuthConfig.confirm?(cfg),
      reset?: AuthConfig.reset?(cfg),
      custom_marker: Gen.Custom.marker_block()
    ]
  end

  # --- AuthConfig value extraction ---------------------------------------

  defp session_values(%AuthConfig{session: nil}), do: {30, 365, 5}

  defp session_values(%AuthConfig{session: opts}) do
    {
      ttl_days(opts[:ttl], 30),
      ttl_days(opts[:remember_me], 365),
      Keyword.get(opts, :max_sessions, 5)
    }
  end

  defp api_token_ttl_days(%AuthConfig{} = cfg) do
    case AuthConfig.strategy_opts(cfg, :api_token) do
      nil -> 90
      opts -> ttl_days(opts[:ttl], 90)
    end
  end

  defp api_token_max(%AuthConfig{} = cfg) do
    case AuthConfig.strategy_opts(cfg, :api_token) do
      nil -> 5
      opts -> Keyword.get(opts, :max_tokens, 5)
    end
  end

  defp api_token_scopes(%AuthConfig{} = cfg) do
    case AuthConfig.strategy_opts(cfg, :api_token) do
      nil -> [:read, :write]
      opts -> Keyword.get(opts, :scopes, [:read, :write])
    end
  end

  defp ttl_days(nil, default), do: default
  defp ttl_days({n, :days}, _), do: n
  defp ttl_days({n, :hours}, _), do: max(div(n, 24), 1)
  defp ttl_days(_, default), do: default

  defp ttl_hours(nil, default), do: default

  defp ttl_hours(opts, default) when is_list(opts) do
    case Keyword.get(opts, :token_ttl) do
      nil -> default
      {n, :hours} -> n
      {n, :days} -> n * 24
      _ -> default
    end
  end

  # --- Misc --------------------------------------------------------------

  defp require_auth_entity!(%Domain{} = domain) do
    case Domain.auth_entity(domain) do
      nil ->
        raise Caravela.GenError,
          message: "#{inspect(domain.module)} has no entity with an `authenticatable` block",
          suggestion:
            "Add one before running `mix caravela.gen.auth`:\n\n" <>
              "    entity :users do\n" <>
              "      field :email, :string, required: true\n" <>
              "      authenticatable do\n" <>
              "        strategy :password\n" <>
              "      end\n" <>
              "    end",
          docs_url: "https://hexdocs.pm/caravela/auth.html"

      entity ->
        entity
    end
  end

  defp assert_auth!(%Domain{} = domain), do: require_auth_entity!(domain)

  defp existing_path(path, opts) do
    root = Keyword.get(opts, :root, File.cwd!())
    Path.join(root, path)
  end

  defp default_timestamp do
    {{y, mo, d}, {h, mi, s}} = :calendar.universal_time()

    :io_lib.format("~4..0B~2..0B~2..0B~2..0B~2..0B~2..0B", [y, mo, d, h, mi, s])
    |> IO.iodata_to_binary()
  end
end
