defmodule Caravela.Gen.LiveView do
  @moduledoc """
  Generates Phoenix LiveView modules that mount Svelte components via
  LiveSvelte.

  Output per entity (`:books`):

    * `index.ex` — list + delete + navigate-to-edit
    * `show.ex` — single-record view
    * `form.ex` — create + edit, with validate round-trips

  Every LiveView delegates to the context module generated by
  `Caravela.Gen.Context`, so authorization, hooks, and (when enabled)
  tenant scoping apply automatically. The frontend (the Svelte
  component) receives props reflecting the socket assigns and sends
  events back via LiveSvelte's `pushEvent`.

  Returns a list of `{path, source}` tuples. Files preserve content
  below the `# --- CUSTOM ---` marker on regeneration.
  """

  alias Caravela.Schema.{Domain, Entity}
  alias Caravela.{Gen, Naming, Tenant}

  @index_template Path.expand("../../../priv/templates/live_index.eex", __DIR__)
  @show_template Path.expand("../../../priv/templates/live_show.eex", __DIR__)
  @form_template Path.expand("../../../priv/templates/live_form.eex", __DIR__)
  @form_with_domain_template Path.expand(
                               "../../../priv/templates/live_form_with_domain.eex",
                               __DIR__
                             )
  @form_domain_template Path.expand("../../../priv/templates/live_form_domain.eex", __DIR__)

  @doc """
  Render every LiveView for every entity.

  Options:

    * `:root` — project root for reading existing files (CUSTOM merge)
    * `:with_domain` — when `true`, also emit a `Caravela.Live.Domain`
      module per entity and render the form LiveView from the
      Template-backed variant. Index and show stay plain regardless.
  """
  def render_all(%Domain{} = domain, opts \\ []) do
    domain.entities
    |> Enum.filter(&(&1.frontend == :live))
    |> Enum.flat_map(fn entity ->
      base = [
        render_entity(domain, entity, :index, opts),
        render_entity(domain, entity, :show, opts),
        render_entity(domain, entity, :form, opts)
      ]

      if Keyword.get(opts, :with_domain, false) do
        base ++ [render_form_domain(domain, entity, opts)]
      else
        base
      end
    end)
  end

  @doc "Render a single LiveView. `kind` is `:index`, `:show`, or `:form`."
  def render_entity(%Domain{} = domain, %Entity{} = entity, kind, opts \\ []) do
    path = Naming.live_file_path(domain, entity.name, kind)
    root = Keyword.get(opts, :root, File.cwd!())
    existing = Path.join(root, path)

    assigns = build_assigns(domain, entity, kind, opts)

    source =
      EEx.eval_file(template_for(kind, opts), assigns: assigns, trim: true)
      |> Gen.Custom.merge_with_file(existing, opts)
      |> Caravela.Gen.Format.try_format()
      |> Gen.Custom.stamp_header(generator: :"live_view_#{kind}")

    {path, source}
  end

  @doc "Render the `*_domain.ex` companion module for an entity."
  def render_form_domain(%Domain{} = domain, %Entity{} = entity, opts \\ []) do
    path = form_domain_file_path(domain, entity)
    root = Keyword.get(opts, :root, File.cwd!())
    existing = Path.join(root, path)

    assigns = [
      module: form_domain_module(domain, entity),
      domain_module: domain.module,
      singular: Naming.singular_string(entity.name),
      custom_marker: Gen.Custom.marker_block()
    ]

    source =
      EEx.eval_file(@form_domain_template, assigns: assigns, trim: true)
      |> Gen.Custom.merge_with_file(existing, opts)
      |> Caravela.Gen.Format.try_format()
      |> Gen.Custom.stamp_header(generator: :live_view_form_domain)

    {path, source}
  end

  defp template_for(:index, _opts), do: @index_template
  defp template_for(:show, _opts), do: @show_template

  defp template_for(:form, opts) do
    if Keyword.get(opts, :with_domain, false),
      do: @form_with_domain_template,
      else: @form_template
  end

  # Sibling file to `<entity>_live/form.ex`:
  #   lib/<web>/live/[v1/]<context>/<entity>_live/form_domain.ex
  defp form_domain_file_path(%Domain{} = domain, %Entity{} = entity) do
    domain
    |> Naming.live_file_path(entity.name, :form)
    |> Path.dirname()
    |> Path.join("form_domain.ex")
  end

  # Sibling to `<Web>.[V1.]<Context>.<Entity>Live.Form`, named
  # `<...>.<Entity>Live.FormDomain`. Keep the name flat (one segment,
  # not `Form.Domain`) so imports read naturally.
  defp form_domain_module(%Domain{} = domain, %Entity{} = entity) do
    parent =
      domain
      |> Naming.live_module(entity.name, :index)
      |> Module.split()
      |> Enum.drop(-1)
      |> Module.concat()

    Module.concat(parent, "FormDomain")
  end

  # --- Assigns -----------------------------------------------------------

  defp build_assigns(%Domain{} = domain, %Entity{} = entity, kind, opts) do
    singular = Naming.singular_string(entity.name)
    plural = Naming.plural_string(entity.name)
    context_module = Naming.context_module(domain)
    [context_short | _] = context_module |> Module.split() |> Enum.reverse()
    entity_module = Naming.entity_module(domain, entity.name)
    [entity_short | _] = entity_module |> Module.split() |> Enum.reverse()

    index_path = route_prefix(domain, entity)
    edit_path = index_path <> "/"
    new_path = index_path <> "/new"

    attrs_fields =
      entity.fields
      |> Enum.reject(&Tenant.injected?/1)
      |> Enum.map(& &1.name)

    decimal_fields =
      entity.fields
      |> Enum.filter(&(&1.type == :decimal))
      |> Enum.map(& &1.name)

    [
      module: Naming.live_module(domain, entity.name, kind),
      domain_module: domain.module,
      entity_name: entity.name,
      context_module: context_module,
      context_short: context_short,
      entity_module: entity_module,
      entity_short: entity_short,
      form_domain_module: form_domain_module(domain, entity),
      with_domain: Keyword.get(opts, :with_domain, false),
      web_module_alias: Naming.web_module(domain) |> inspect(),
      component_ref: Naming.svelte_component_ref(domain, entity.name, kind),
      singular: singular,
      plural: plural,
      list_fn: "list_#{plural}",
      get_fn: "get_#{singular}",
      create_fn: "create_#{singular}",
      update_fn: "update_#{singular}",
      delete_fn: "delete_#{singular}",
      change_fn: "change_#{singular}",
      attrs_fields: attrs_fields,
      decimal_fields: decimal_fields,
      index_path: index_path,
      edit_path: edit_path,
      new_path: new_path,
      multi_tenant: Domain.multi_tenant?(domain),
      custom_marker: Gen.Custom.marker_block()
    ]
  end

  # Browser URL prefix for the entity. Mirrors the router scope
  # convention: `/library/books` (or `/v1/library/books` when
  # versioned). The exact routes are still up to the developer — we
  # print a snippet in the mix task.
  defp route_prefix(%Domain{} = domain, %Entity{} = entity) do
    ctx_short = Naming.context_short(domain)
    plural = Naming.plural_string(entity.name)

    case Domain.version(domain) do
      nil -> "/#{ctx_short}/#{plural}"
      v -> "/#{v}/#{ctx_short}/#{plural}"
    end
  end
end
